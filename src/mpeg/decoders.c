/*
The three ASSIGN macros fill a table in groups: every code of a length stands for one value, and takes
up as many entries as there are ways to continue it to the table's index width.

The macros are load-bearing, not a convenience. The build used -g, and cc1 2.7.2 puts a nop in front of
a loop that directly follows a label when no line-number note separates the two. Retail has that nop
where two loops of one macro invocation meet (the second inner loop of every ASSIGN3 group) and
nowhere else, so those loops began on one source line.

guess: the names and the parameter names are those of the ASSIGN macros in the Berkeley mpeg_play
decoder (decoders.c), whose bodies these functions reproduce statement for statement.
*/
#define ASSIGN1( start, end, step, val, num ) \
    for ( i = start; i < end; i += step ) { \
        for ( j = 0; j < step; j++ ) { \
            D_80103480[i + j].value = val; \
            D_80103480[i + j].num_bits = num; \
        } \
        val--; \
    }

